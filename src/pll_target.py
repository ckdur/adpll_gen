# Design target of the PLL for the characterized technology (sim/outputs/<PDK>)
#
# Reads the ngspice characterization (delay lines, mux/SS-BBPD, injection window) and derives:
#   - the band of f_OUT the technology supports (tuning range with PVT margin, injection/SS-BBPD timing)
#   - f_OUT = N f_REF: the highest multiple of f_REF in the band where the bang-bang loop pulls in with a
#     proportional step beta_p <= 1 % of T_OUT (see pll_model.design)
#   - K_P/K_I: the smallest gains that pull in from any initial fine code (noise-free behavioral model)
#   - the gains after LOCKED (gear shifting): minimum rms jitter with the ISF DCO noise (if test_dco_noise
#     has run), among the gains that hold the lock
# Any of N (as FCW = N - 2), K_P, K_I can be fixed from lib/<PDK>.mk (PLL_FCW, PLL_KP, PLL_KI,
# PLL_KP_LOCKED, PLL_KI_LOCKED). Fixed acquisition gains disable the automatic gear shifting.
#
# Writes (in the current directory):
#   pll_target.vh:   `defines for src/pll_test.v (TB_REF_T, TB_FCW, TB_KP, TB_KI[, TB_KP/KI_LOCKED])
#   pll_target.json: everything, for the design notebook
#
# usage: python3 pll_target.py --f-ref 100e6 [--fcw 8] [--kp 3967 --ki 257]

import argparse, json, os, sys
import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pll_model as pm


def opt_int(s):
    return int(float(s)) if s not in (None, "") else None


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--f-ref", type=float, default=100e6)
    p.add_argument("--fcw", type=opt_int, default=None, help="FCW = N - 2 (empty: automatic)")
    p.add_argument("--kp", type=opt_int, default=None)
    p.add_argument("--ki", type=opt_int, default=None)
    p.add_argument("--kp-locked", type=opt_int, default=None, help="Gains after LOCKED (empty: automatic,")
    p.add_argument("--ki-locked", type=opt_int, default=None, help="  from the DCO noise of test_dco_noise)")
    p.add_argument("--no-gear", action="store_true", help="Same gains before and after LOCKED")
    p.add_argument("--sim-out", default=".")
    a = p.parse_args()
    if (a.kp is None) != (a.ki is None):
        sys.exit("Give both --kp and --ki (or none)")

    ch = pm.load_characterization(a.sim_out)
    inj = pm.injection_timing(a.sim_out, ch)
    N = a.fcw + 2 if a.fcw is not None else None
    d = pm.design(ch, inj, a.f_ref, N=N, KP=a.kp, KI=a.ki)
    lims = d["limits"]
    print("\nSupported band of f_OUT:")
    for k, (lo, hi) in lims["limits"].items():
        print(f"  {k:32s} {lo/1e9:7.3f} - {hi/1e9:7.3f} GHz")
    print(f"  => {lims['f_lo']/1e9:.3f} - {lims['f_hi']/1e9:.3f} GHz")
    print(f"Tuning-curve coverage: fine range / max mid step = {lims['coverage']['fine_vs_mid']:.2f}, "
          f"mid range / max coarse step = {lims['coverage']['mid_vs_coarse']:.2f} (must be > 1)")
    if d["N"] is None:
        sys.exit("No feasible design target: see the table above (relax PLL_F_REF or the gains)")

    # Gear shifting: lower gains after LOCKED, optimized for jitter with the simulated DCO noise
    gear = None
    if a.kp_locked is not None:
        gear = (a.kp_locked, a.ki_locked, None, None, [])
    elif not a.no_gear and a.kp is None:
        dco = pm.dco_noise_for(ch, d["f_out"])
        if dco is None:
            print("No DCO noise (test_dco_noise.csv): no gear shifting")
        else:
            cfg = pm.PLLConfig(f_ref=a.f_ref, N=d["N"])
            gear = pm.choose_locked_gains(cfg, ch, d["coarse"], d["mid"], dco, kp_max=d["KP"])
            if gear is not None and gear[0] >= d["KP"]:
                gear = None                       # The pull-in gains are already the best ones

    T_ref_fs = int(round(1e15 / a.f_ref))
    fcw = d["N"] - 2
    with open(os.path.join(a.sim_out, "pll_target.vh"), "w") as f:
        f.write(f"""// Generated by src/pll_target.py from the characterization of this PDK (do not edit)
// f_REF = {a.f_ref/1e6:g} MHz, N = {d['N']}, f_OUT = {d['f_out']/1e9:.4g} GHz, expected coarse/mid = {d['coarse']}/{d['mid']}
`define TB_REF_T {T_ref_fs}
`define TB_FCW 'd{fcw}
`define TB_KP 'd{d['KP']}
`define TB_KI 'd{d['KI']}
""")
        if gear is not None:
            f.write(f"""// Gains after LOCKED (gear shifting)
`define TB_KP_LOCKED 'd{gear[0]}
`define TB_KI_LOCKED 'd{gear[1]}
""")
    out = dict(f_ref=a.f_ref, N=d["N"], fcw=fcw, f_out=d["f_out"], KP=d["KP"], KI=d["KI"],
               coarse=int(d["coarse"]), mid=int(d["mid"]), fine_fraction=float(d["frac"]),
               beta_p=float(d["beta_p"]), fixed=dict(N=N is not None, gains=a.kp is not None),
               KP_locked=gear[0] if gear else None, KI_locked=gear[1] if gear else None,
               jitter_locked=[gear[2], gear[3]] if gear and gear[2] is not None else None,
               locked_sweep=[[int(r[0]), int(r[1]), bool(r[2]), float(r[3]), float(r[4])] for r in gear[4]] if gear else [],
               f_lo=lims["f_lo"], f_hi=lims["f_hi"],
               limits={k: [float(v[0]), float(v[1])] for k, v in lims["limits"].items()},
               coverage={k: float(v) for k, v in lims["coverage"].items()},
               injection={k: (float(v) if v is not None else None) for k, v in inj.items()},
               gain_sweep=[[int(k), int(i), bool(o)] for k, i, o in d["gain_sweep"]],
               tried=[[int(n), [int(c[0]), int(c[1]), float(c[2])] if c else None, kp, why] for n, c, kp, why in d["tried"]])
    with open(os.path.join(a.sim_out, "pll_target.json"), "w") as f:
        json.dump(out, f, indent=1)
    print(f"\nTarget: f_OUT = {d['f_out']/1e9:.4g} GHz (N = {d['N']}, FCW = {fcw}), K_P/K_I = {d['KP']}/{d['KI']}, "
          f"beta_p = {100*d['beta_p']:.2f} % of T_OUT" + (f", after LOCKED {gear[0]}/{gear[1]}" if gear else "")
          + ". Written pll_target.vh and pll_target.json")


if __name__ == "__main__":
    main()
