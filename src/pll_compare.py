#!python
# Comparison of the PLL designs of every characterized technology
# Reads sim/outputs/<PDK>/report/summary.json (written by src/pll_design.ipynb, `make -C sim PDK=<PDK> report`)
# and writes sim/outputs/compare.md and compare.html
#
# usage: python3 pll_compare.py <sim/outputs>

import glob, json, os, sys

out_dir = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else "../sim/outputs")
S = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(out_dir, "*", "report", "summary.json")))]
if not S:
    sys.exit("No summary.json: run make -C sim PDK=<PDK> report first")

ps = lambda x: f"{x*1e12:.3g} ps"
def rtl(s, k):
    r = s["rtl"].get(k)
    if not r:
        return "not run"
    if not r["t_lock"]:
        return "**not locked**"
    tie = f", TIE {ps(r['tie'])} (noise-free)" if r.get("tie") is not None else ""
    return f"lock {r['t_lock']*1e6:.2f} µs, {r['glitches']} glitches{tie}"
rows = [
    ("DCO tuning range (all codes)", lambda s: f"{s['tuning'][0]/1e9:.3f} – {s['tuning'][1]/1e9:.3f} GHz"),
    ("Supported band (PVT + injection timing)", lambda s: f"{s['band'][0]/1e9:.3f} – {s['band'][1]/1e9:.3f} GHz" if s["band"] else "–"),
    ("Tuning-curve coverage fine/mid, mid/coarse (> 1)", lambda s: f"{s['coverage']['fine_vs_mid']:.2f}, {s['coverage']['mid_vs_coarse']:.2f}" if s["coverage"] else "–"),
    ("Design: f_OUT = N × f_REF", lambda s: f"{s['f_out']/1e9:.4g} GHz = {s['N']} × {s['f_ref']/1e6:g} MHz"),
    ("Fine resolution (period) / K_DCO", lambda s: f"{s['fine_lsb']*1e15:.0f} fs / {s['f_out']**2*s['fine_lsb']/1e3:.0f} kHz"),
    ("Mux delay", lambda s: ps(s["tmux"])),
    ("Injection window margins (early / late)", lambda s: f"{ps(s['inj_margins'][0])} / {ps(s['inj_margins'][1])}"),
    ("DCO free-running L(1 MHz) at f_OUT", lambda s: f"{s['dco_L1M']:.1f} dBc/Hz ({s['dco_source']})"),
    ("DCO 1/f³ corner", lambda s: f"{s['dco_corner']/1e6:.2f} MHz"),
    ("K_P/K_I acquisition → after LOCKED", lambda s: f"{s['KP_acq']}/{s['KI_acq']} → {s['KP']}/{s['KI']}"),
    ("Jitter-transfer bandwidth", lambda s: f"{s['bw']/1e6:.1f} MHz"),
    ("rms jitter, no injection / injection", lambda s: f"{ps(s['jitter'][0])} / {ps(s['jitter'][1])}"),
    ("RTL, no injection", lambda s: rtl(s, "noinj")),
    ("RTL, injection", lambda s: rtl(s, "inj")),
]
md = ["# ADPLL across technologies", "",
      "Generated by `src/pll_compare.py` from the design reports (`make -C sim PDK=<PDK> report`). "
      f"Jitter: behavioral model, {S[0]['jitter_band'][0]/1e3:g} kHz – {S[0]['jitter_band'][1]/1e6:g} MHz.", "",
      "| | " + " | ".join(f"`{s['pdk']}`" for s in S) + " |", "|---|" + "---|" * len(S)]
for name, fn in rows:
    md.append(f"| {name} | " + " | ".join(fn(s) for s in S) + " |")
txt = "\n".join(md) + "\n"
open(os.path.join(out_dir, "compare.md"), "w").write(txt)
try:
    import markdown
    body = markdown.markdown(txt, extensions=["tables"])
except ImportError:
    body = "<pre>" + txt + "</pre>"
open(os.path.join(out_dir, "compare.html"), "w").write(
    "<!doctype html><meta charset=utf-8><title>ADPLL across technologies</title>"
    "<style>body{font-family:sans-serif;margin:2em}td,th{border:1px solid #ccc;padding:4px 8px}table{border-collapse:collapse}</style>"
    + body)
print(txt)
