import sys
from spice_io import read_meas

def convert_simulation_to_verilog(fil):
    meas = read_meas(fil)

    # Convert all values to the nearest integer, in fento-seconds
    str = ""
    v1 = meas["tmux"]
    iv1 = int(v1 * 1e15)
    str = str + (f"    always @(OUT_WIRE) OUT <= #({iv1}) OUT_WIRE; // tmux = {v1}\n")
    
    v2 = meas["tssbbpd"]
    iv2 = int(v2 * 1e15)
    str = str + (f"    always @(SS_BBPD_WIRE) SS_BBPD <= #({iv2}) SS_BBPD_WIRE; // tssbbpd = {v2}\n")

    # The two dummy inverters are the same cells, so INJ_LVL has the delay of OSC_LVL
    v3 = meas["tlvl"]
    iv3 = int(v3 * 1e15)
    str = str + (f"    always @(FINE_OUT) OSC_LVL <= #({iv3}) FINE_OUT; // tlvl = {v3}\n")
    str = str + (f"    always @(INJ_EDGE) INJ_LVL <= #({iv3}) INJ_EDGE; // tlvl = {v3}\n")

    # Window latch (sym_mux/WIN): delays from INJ_WIN when it opens (DCO low) and when it closes
    v4, v5 = meas["twin_on"], meas["twin_off"]
    str = str + (f"    always @(WIN_D) WIN <= #(WIN_D ? {int(v4 * 1e15)} : {int(v5 * 1e15)}) WIN_D; // twin_on = {v4}, twin_off = {v5}\n")

    return str

always_str = convert_simulation_to_verilog(sys.argv[1])

str = f"""// NOTE: Automatically generated by create_sim_sym.py
// Digital-simulated definition of
// The total implementation of Symmetrical Multiplexer and Symmetrical SSBBPD

module sim_SYM (
    inout VDD, VSS, // ignored
    input INJ_WIN, DCO_EN,
    input INJ_EDGE, FINE_OUT,
    output reg [1:0] SS_BBPD,
    output reg OUT,
    output reg OSC_LVL, INJ_LVL  // Dummy inverters: !OSC_BALANCED, !INJ_EDGE_BALANCED
);
    // Symmetric balancer (Nothing)
    wire OSC_BALANCED, INJ_EDGE_BALANCED;
    assign OSC_BALANCED = !FINE_OUT;
    assign INJ_EDGE_BALANCED = !INJ_EDGE;

    // Guarded window (sym_mux.v): opens only if the DCO is still low when INJ_WIN rises (otherwise this
    // injection is skipped), closes with INJ_WIN
    reg WIN_D = 1'b0, WIN = 1'b0, SKIP = 1'b0;
    always @(*) begin
        if(!INJ_WIN) begin
            WIN_D = 1'b0;
            SKIP = 1'b0;
        end else begin
            if(!OSC_LVL && !WIN_D) SKIP = 1'b1;
            if(OSC_LVL && !SKIP) WIN_D = 1'b1;
        end
    end

    // Sym. MUX
    wire DCO_EN_INJ_WIN;
    assign DCO_EN_INJ_WIN = !(!DCO_EN || WIN); // NOR2B

    wire OSC_INJ, REF_INJ;
    assign REF_INJ = !(INJ_EDGE_BALANCED && WIN); // NAND2
    assign OSC_INJ = !(OSC_BALANCED && DCO_EN_INJ_WIN); // NAND2
    wire OUT_WIRE = !(REF_INJ && OSC_INJ);

    // Subsampling bang-bang PD (SS-BBPD)
    wire [1:0] SS_BBPD_WIRE;
    sim_SSBBPD ssbbpd_impl(
        .CLK_REF(INJ_EDGE_BALANCED), .CLK_VCO(OSC_BALANCED),
        .SS_BBPD(SS_BBPD_WIRE));

    // Transport delays (non-blocking): glitches propagate instead of being lost
{always_str}

endmodule
"""

